          END);

      -- acute_neurological_syndrome (meningitis belt = sahel, dry season spike)
      INSERT INTO weekly_counts (district_id, syndrome_category, week_start, count) VALUES
        (dist_rec.district_id, 'acute_neurological_syndrome', w_start,
          CASE dist_rec.cz
            WHEN 'sahel' THEN 4 + (random()*6)::int + (CASE WHEN week_num > 6 THEN (random()*5)::int ELSE 0 END)
