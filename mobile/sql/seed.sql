      INSERT INTO weekly_counts (district_id, syndrome_category, week_start, count) VALUES
        (dist_rec.district_id, 'acute_febrile_illness', w_start,
          CASE dist_rec.cz
            WHEN 'forest' THEN 22 + (random()*15)::int
            WHEN 'tropical' THEN 18 + (random()*12)::int
            WHEN 'sahel' THEN 10 + (random()*8)::int
            ELSE 5 + (random()*5)::int
          END);

      -- acute_respiratory_infection
      INSERT INTO weekly_counts (district_id, syndrome_category, week_start, count) VALUES
        (dist_rec.district_id, 'acute_respiratory_infection', w_start,
          CASE dist_rec.cz
