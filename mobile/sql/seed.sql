      'c0000000-0000-4000-8000-00000000d001', -- Bissau Central (forest)
      'c0000000-0000-4000-8000-00000000e001'  -- Praia (arid)
    )
  LOOP
    FOR week_num IN 0..11 LOOP
      w_start := '2025-11-17'::date + (week_num * 7);

      -- acute_watery_diarrhea
      INSERT INTO weekly_counts (district_id, syndrome_category, week_start, count) VALUES
        (dist_rec.district_id, 'acute_watery_diarrhea', w_start,
          CASE dist_rec.cz
            WHEN 'sahel' THEN 18 + (random()*12)::int + (CASE WHEN week_num > 8 THEN (random()*8)::int ELSE 0 END)
            WHEN 'forest' THEN 6 + (random()*6)::int
            WHEN 'arid' THEN 4 + (random()*4)::int
            ELSE 10 + (random()*8)::int
          END);

